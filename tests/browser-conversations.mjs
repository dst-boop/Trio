// Run against a local mock server on port 8000 with APP_PASSWORD=local-browser-test.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' });
const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept('local-browser-test'));
await page.goto('http://127.0.0.1:8000/');
await page.getByText('Demo mode: answers are fake.', { exact: false }).waitFor();
await page.getByRole('textbox', { name: 'Your question' }).fill('Remember this browser test');
await page.getByRole('button', { name: 'Ask all three', exact: true }).click();
await page.waitForURL(/\/c\/[A-Za-z0-9_-]{32}$/);
await page.getByText('Saved on this server', { exact: true }).waitFor();
const savedUrl = page.url();
await page.reload();
await page.getByText('Saved conversation · Read-only').waitFor();
assert.equal(await page.locator('#form').isVisible(), false);
assert.equal(await page.locator('.final').count(), 1);
await page.getByText('See what each model said').click();
assert.equal(await page.locator('.piece').count(), 3);
await page.getByRole('button', { name: 'Continue conversation', exact: true }).click();
await page.getByRole('textbox', { name: 'Your question' }).fill('A follow-up question');
await page.getByRole('button', { name: 'Ask all three', exact: true }).click();
await page.waitForFunction(() => document.querySelectorAll('.final').length === 2 && document.querySelector('#go').textContent === 'Ask all three');
assert.equal(page.url(), savedUrl);
await page.reload();
await page.getByText('Saved conversation · Read-only').waitFor();
assert.equal(await page.locator('.final').count(), 2);
await page.setViewportSize({ width: 390, height: 844 });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
const stranger = await browser.newPage();
stranger.on('dialog', dialog => dialog.dismiss());
await stranger.goto(savedUrl);
assert.equal(await stranger.locator('.final').count(), 0);
const response = await stranger.request.get(savedUrl.replace('/c/', '/api/conversations/'));
assert.equal(response.status(), 401);
await page.getByRole('link', { name: 'New conversation', exact: true }).click();
assert.equal(page.url(), 'http://127.0.0.1:8000/');
assert.equal(await page.locator('.final').count(), 0);
assert.deepEqual(errors, []);
await browser.close();
console.log('Conversation browser checks passed: create, refresh, full contributions, read-only links, continue, mobile, password gating, new conversation.');
