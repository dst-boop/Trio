import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.TRIO_BASE_URL || 'http://localhost:5173';
const browser = await chromium.launch({ headless:true, channel:process.env.PLAYWRIGHT_CHANNEL || 'msedge' });
const context = await browser.newContext({viewport:{width:1440,height:1050}}), page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const headers={'X-Trio-Account':'local_seedy',Origin:base};
const api='/api/connections';
try {
  await page.goto(base+'/signin-with-chatgpt?return_to=%2Fworkspace',{waitUntil:'networkidle'});
  let metadata=await (await context.request.get(base+api,{headers})).json();
  assert.ok(metadata.connections,'Local D1 migrations must be applied before the test');
  for(const item of metadata.connections.filter(item=>item.saved)) assert.equal((await context.request.delete(base+api,{headers,data:{provider:item.provider,revision:item.revision}})).status(),200);
  await page.reload({waitUntil:'networkidle'});
  const open=async()=>{await page.getByRole('button',{name:'Connections',exact:true}).click();await page.getByText('Saved keys are private to this account.',{exact:false}).waitFor();};
  await open();
  const first=page.locator('.connection-row').nth(0);
  await first.getByLabel('API key',{exact:true}).fill('synthetic-browser-key');
  await first.getByLabel('Model ID',{exact:true}).fill('synthetic-model');
  await first.getByRole('button',{name:'Save to account',exact:true}).click();
  await first.getByText('Saved to your account',{exact:true}).waitFor();
  assert.equal(await first.getByLabel('API key',{exact:true}).inputValue(),'');
  metadata=await (await context.request.get(base+api,{headers})).json();
  const initial=metadata.connections.find(item=>item.provider==='openai');
  assert.ok(initial.saved);assert.ok(!JSON.stringify(metadata).includes('synthetic-browser-key'));assert.equal(initial.model,'synthetic-model');
  await page.reload({waitUntil:'networkidle'});await open();
  await first.getByText('Saved to your account',{exact:true}).waitFor();
  assert.equal(await first.getByLabel('Model ID',{exact:true}).inputValue(),'synthetic-model');
  let checked;
  await page.route('**/api/connections/check',async route=>{checked=route.request().postDataJSON();assert.equal(route.request().headers()['x-trio-account'],'local_seedy');await route.fulfill({json:{status:'checked'}});});
  await first.getByRole('button',{name:'Check access',exact:true}).click();await first.getByText('Access checked',{exact:true}).waitFor();
  assert.equal(checked.key,'__TRIO_SAVED_KEY__');
  await page.goto(base+'/signout-with-chatgpt?return_to=%2F',{waitUntil:'networkidle'});
  assert.equal((await context.request.get(base+api,{headers})).status(),401);
  await page.goto(base+'/signin-with-chatgpt?return_to=%2Fworkspace',{waitUntil:'networkidle'});await open();
  await first.getByText('Saved to your account',{exact:true}).waitFor();
  assert.equal(await first.getByLabel('API key',{exact:true}).inputValue(),'');
  // Concurrent replacement: stale UI must keep typed input and explicitly refresh.
  assert.equal((await context.request.put(base+api,{headers,data:{provider:'openai',revision:initial.revision,key:'other-tab-key',model:'other-model',enabled:true}})).status(),200);
  await first.getByLabel('API key',{exact:true}).fill('replacement-browser-key');
  await first.getByRole('button',{name:'Save replacement',exact:true}).click();
  await page.getByText('Saved keys changed in another tab.',{exact:false}).waitFor();
  assert.equal(await first.getByLabel('API key',{exact:true}).inputValue(),'replacement-browser-key');
  await page.getByRole('button',{name:'Reload saved connections',exact:true}).click();
  await page.getByText('Saved keys are private to this account.',{exact:false}).waitFor();
  assert.equal(await first.getByLabel('API key',{exact:true}).inputValue(),'replacement-browser-key');
  await first.getByRole('button',{name:'Save replacement',exact:true}).click();await first.getByText('Saved to your account',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Clear keys from this tab',exact:true}).click();await first.getByText('No key added',{exact:true}).waitFor();
  assert.ok((await (await context.request.get(base+api,{headers})).json()).connections[0].saved);
  await page.getByRole('button',{name:'Reload saved connections',exact:true}).click();await first.getByText('Saved to your account',{exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.equal(await page.locator('[role=dialog]').evaluate(el=>el.scrollWidth>el.clientWidth),false);
  await mkdir('test-output',{recursive:true});await page.screenshot({path:'test-output/saved-credentials-mobile.png'});
  await first.getByRole('button',{name:'Delete saved key',exact:true}).click();
  await page.getByRole('alertdialog').getByRole('button',{name:'Delete saved key',exact:true}).click();
  await first.getByText('Not saved to your account',{exact:true}).waitFor();
  await page.reload({waitUntil:'networkidle'});await open();await first.getByText('Not saved to your account',{exact:true}).waitFor();
  assert.equal(await first.getByLabel('API key',{exact:true}).inputValue(),'');
  const browserStorage=await page.evaluate(()=>JSON.stringify({local:localStorage,session:sessionStorage}));
  for(const key of ['synthetic-browser-key','replacement-browser-key','other-tab-key']) assert.ok(!browserStorage.includes(key));
  assert.equal((await context.request.get(base+api,{headers:{...headers,'X-Trio-Account':'different-account'}})).status(),401);
  assert.deepEqual(errors,[]);
  console.log('Saved key browser checks passed: explicit save, metadata only, reload, sign-out/sign-in, replacement, conflict recovery, temporary disconnect, deletion, account pin, no browser persistence, mobile.');
} finally {await browser.close();}
