const baseUrl = process.env.TRIO_BASE_URL || 'http://localhost:5173';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${baseUrl}/signin-with-chatgpt?return_to=%2Fdemo`, { waitUntil: 'networkidle' });
  assert.equal(await page.getByRole('switch', { name: 'Web research', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Connections', exact: true }).click();
  await page.getByPlaceholder('Paste your API key').nth(1).fill('fake-claude-research');
  await page.getByRole('switch', { name: 'Demo mode', exact: true }).click();
  await page.getByRole('switch', { name: 'Remember sessions on this device', exact: true }).click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('switch', { name: 'Web research', exact: true }).click();
  if (await page.getByLabel('Research provider', { exact: true }).count()) await page.getByLabel('Research provider', { exact: true }).selectOption('openai');
  await page.getByRole('textbox', { name: 'Your question' }).fill('Research current facts');
  await page.getByRole('button', { name: 'Ask Trio', exact: true }).click();
  await page.getByRole('heading', { name: 'Connect your AI team' }).waitFor();
  await page.getByText('Web research requires an enabled OpenAI API connection.').waitFor();
  await page.getByPlaceholder('Paste your API key').first().fill('fake-openai-research');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  const research = { text: 'Evidence from [the report](https://example.org/report).', sources: [{ title: 'Primary report', url: 'https://example.org/report' }], at: '2026-09-22T12:00:00.000Z' };
  let calls = 0;
  await page.route('**/api/ask', async route => {
    calls++; const body = route.request().postDataJSON(); assert.equal(body.webResearch, calls === 1);
    const result = { drafts: { openai: 'Perspective', claude: 'Another perspective' }, reviews: {}, answer: `Answer ${calls}`, by: 'openai', errors: [], seconds: 1, demo: false, ...(calls === 1 ? { researchRequested: true, research } : {}) };
    await route.fulfill({ contentType: 'application/x-ndjson', body: (calls === 1 ? [{ type: 'stage', stage: 'research' }, { type: 'research', research }, { type: 'stage', stage: 'draft' }, { type: 'final', result }] : [{ type: 'final', result }]).map(e => JSON.stringify(e)).join('\n') + '\n' });
  });
  const ask = async question => { await page.getByRole('textbox', { name: 'Your question' }).fill(question); await page.getByRole('button', { name: 'Ask Trio', exact: true }).click(); await page.getByRole('button', { name: 'Ask Trio', exact: true }).waitFor(); };
  await ask('Research current facts');
  await page.getByText('Answer 1', { exact: true }).waitFor();
  await page.locator('.research-panel summary').click();
  assert.equal(await page.getByRole('link', { name: 'the report', exact: true }).getAttribute('href'), research.sources[0].url);
  await page.getByRole('link', { name: 'Primary report', exact: false }).waitFor();
  const saved = await page.evaluate(() => localStorage.getItem('trio-sessions'));
  assert.ok(saved.includes(research.sources[0].url)); assert.ok(!saved.includes('fake-openai-research')); assert.ok(!saved.includes('fake-claude-research'));
  const downloadEvent = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export session as Markdown' }).click();
  const download = await downloadEvent; let exported = ''; for await (const chunk of await download.createReadStream()) exported += chunk;
  assert.ok(exported.includes(research.sources[0].url)); assert.ok(exported.includes('Shared web research'));
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await mkdir('test-output', { recursive: true }); await page.locator('.research-panel').screenshot({ path: 'test-output/research-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.getByRole('switch', { name: 'Web research', exact: true }).click();
  if (await page.getByLabel('Research provider', { exact: true }).count()) await page.getByLabel('Research provider', { exact: true }).selectOption('openai');
  await ask('Follow up without another search');
  assert.equal(await page.locator('.results-section > .research-panel').count(), 0);
  await page.locator('.previous-turns > summary').click(); await page.getByRole('button', { name: /Question 1/ }).click();
  await page.locator('.history-turn-body .research-panel summary').click(); await page.getByRole('link', { name: 'Primary report', exact: false }).waitFor();
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByText('Answer 2', { exact: true }).waitFor();
  await page.locator('.previous-turns > summary').click(); await page.getByRole('button', { name: /Question 1/ }).click();
  await page.locator('.history-turn-body .research-panel summary').click(); await page.getByRole('link', { name: 'Primary report', exact: false }).waitFor();
  const connections = { openai: { enabled: false, key: '', model: 'model' }, claude: { enabled: true, key: 'fake', model: 'model' }, gemini: { enabled: false, key: '', model: 'model' } };
  const rejected = await page.request.post(baseUrl + '/api/ask', { data: { question: 'q', mode: 'compare', lead: 'claude', webResearch: true, researchProvider: 'openai', connections } });
  assert.equal(rejected.status(), 400); assert.match((await rejected.json()).error, /OpenAI/);
  assert.deepEqual(errors, []);
  console.log('Web research browser checks passed: opt-in, prerequisite, citations, mobile layout, history, export, refresh, and API validation.');
} finally { await browser.close(); }
