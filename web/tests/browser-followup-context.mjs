import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { conversationContext } from '../lib/sessions.ts';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.TRIO_BASE_URL || 'http://localhost:5173';
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const result = { answer: 'An earlier answer', drafts: {}, reviews: {}, errors: [], seconds: 1, demo: false };
const turns = Array.from({ length: 7 }, (_, i) => ({ question: `Earlier question ${i}`, mode: 'fast', result }));
turns.push({ question: 'Compare the alternatives', mode: 'compare', result: { ...result, answer: '', drafts: { openai: 'Alpha perspective. '.repeat(2500), claude: 'Beta perspective. '.repeat(2500), gemini: 'Gamma perspective. '.repeat(2500) } } });
turns.push({ question: 'Prepared demo only', mode: 'fast', result: { ...result, demo: true, answer: 'Prepared demo answer' } });
const fixture = { id: 'context-window', title: 'Long comparison', time: '', turns };
let calls = 0;
try {
  await page.goto(base + '/signin-with-chatgpt?return_to=%2Fdemo', { waitUntil: 'networkidle' });
  await page.evaluate(fixture => { localStorage.setItem('trio-remember', 'true'); localStorage.setItem('trio-sessions', JSON.stringify([fixture])); localStorage.setItem('trio-active-session', fixture.id); }, fixture);
  await page.reload({ waitUntil: 'networkidle' }); assert.equal(await page.locator('.followup-context').count(), 0, 'Demo mode does not send live context');
  await page.getByRole('button', { name: 'Connections', exact: true }).click();
  await page.getByPlaceholder('Paste your API key').first().fill('fake-context-key');
  await page.getByRole('switch', { name: 'Demo mode', exact: true }).click(); await page.getByRole('button', { name: 'Done', exact: true }).click();
  const details = page.locator('.followup-context');
  await details.getByText('Next question uses 6 of 8 earlier live answers · shortened excerpts', { exact: true }).waitFor();
  await details.locator('summary').focus(); await page.keyboard.press('Enter');
  await details.getByText(/2 older exchanges are outside this context window/).waitFor();
  assert.match(await details.textContent(), /1 answer is shortened/);
  await page.setViewportSize({ width: 390, height: 844 }); await details.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await details.evaluate(el => el.scrollWidth > el.clientWidth + 1), false);
  await mkdir('test-output', { recursive: true }); await page.screenshot({ path: 'test-output/followup-context-mobile.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.route('**/api/ask', async route => {
    calls++; const payload = route.request().postDataJSON(); assert.deepEqual(payload.history, conversationContext(turns).messages);
    const comparison = payload.history.at(-1).content;
    assert.equal(comparison.length, 30000);
    for (const name of ['ChatGPT', 'Claude', 'Gemini']) assert.ok(comparison.includes(name + ':\n'));
    assert.equal(comparison.split('[Excerpt shortened; remaining text omitted.]').length, 4);
    assert.ok(!JSON.stringify(payload.history).includes('Prepared demo'));
    assert.ok(!JSON.stringify(payload.history).includes('Earlier question 0'));
    await route.fulfill({ contentType: 'application/x-ndjson', body: JSON.stringify({ type: 'final', result: { ...result, answer: 'Follow-up uses all three excerpts.' } }) + '\n' });
  });
  await page.getByRole('textbox', { name: 'Your question', exact: true }).fill('Compare their main disagreements');
  await page.getByRole('button', { name: 'Ask Trio', exact: true }).click();
  await page.getByText('Follow-up uses all three excerpts.', { exact: true }).waitFor();
  await details.getByText('Next question uses 6 of 9 earlier live answers · shortened excerpts', { exact: true }).waitFor();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('trio-sessions')));
  assert.deepEqual(stored[0].turns.slice(0, turns.length), turns); assert.equal(calls, 1);
  assert.ok(!JSON.stringify(stored).includes('fake-context-key'));
  await page.getByRole('button', { name: /^New session/ }).click(); assert.equal(await details.count(), 0);
  assert.deepEqual(errors, []);
  console.log('Follow-up context passed: exact visible counts and sent history, all long Compare perspectives, omission markers, demo exclusion, mobile/keyboard, updated counts, full stored originals, new-session reset, one mocked model request.');
} finally { await browser.close(); }
